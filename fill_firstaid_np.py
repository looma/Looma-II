def fail(msg):
    print('ERROR:', msg); sys.exit(1)

def main():
    data = json.load(open(SRC, encoding='utf-8'))
    topics = data['topics']
    seen = set()
    for t in topics:
        tid = t['id']
        if tid not in NP:
            fail(f'no translations for topic {tid}')
        seen.add(tid)
        tr = NP[tid]
        t['title']['np'] = tr['title']

        em = t.get('emergency', [])
        if len(em) != len(tr['emergency']):
            fail(f'{tid}: emergency count {len(em)} != {len(tr["emergency"])}')
        for e, np in zip(em, tr['emergency']):
            e['action']['np'] = np

        nv = t.get('never', [])
        if len(nv) != len(tr['never']):
            fail(f'{tid}: never count {len(nv)} != {len(tr["never"])}')
        for n, np in zip(nv, tr['never']):
            n['np'] = np

        ln = t.get('learn', [])
        if len(ln) != len(tr['learn']):
            fail(f'{tid}: learn count {len(ln)} != {len(tr["learn"])}')
        for c, (a, w, tip) in zip(ln, tr['learn']):
            c['action']['np'] = a; c['why']['np'] = w; c['tip']['np'] = tip

        qz = t.get('quiz', [])
        if len(qz) != len(tr['quiz']):
            fail(f'{tid}: quiz count {len(qz)} != {len(tr["quiz"])}')
        for q, (qn, opts, fb) in zip(qz, tr['quiz']):
            q['question']['np'] = qn
            if len(q.get('options', [])) != len(opts):
                fail(f'{tid}: quiz options count mismatch')
            for o, otxt in zip(q['options'], opts):
                o['text']['np'] = otxt
            q['feedback']['np'] = fb

    missing = set(NP) - seen
    if missing:
        fail(f'unused translation blocks: {missing}')

    # sanity: no empty np left anywhere in topics
    def walk(o):
        if isinstance(o, dict):
            if 'en' in o and 'np' in o and o['np'] == '':
                fail(f'still-empty np for en={o["en"][:50]!r}')
            for v in o.values(): walk(v)
        elif isinstance(o, list):
            for v in o: walk(v)
    walk(topics)

    json.dump(data, open(SRC, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print(f'Filled Nepali for {len(seen)} topics in firstaid-source.json')

